// Verificação embutida: avisa no console se alguma palavra quebrar as
// regras, em vez de deixar o jogo falhar sem explicação.
// ------------------------------------------------------------
(function () {
  const semAcento = (t) => t.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();
  const problemas = [];
  const vistas = new Set();

  PALAVRAS_EJAC.forEach((entrada, i) => {
    const limpa = semAcento(entrada.palavra);
    if (!/^[A-Z]+$/.test(limpa)) problemas.push(`#${i} "${entrada.palavra}": tem caractere que não é letra`);
    if (limpa.length < 4 || limpa.length > 10) problemas.push(`#${i} "${entrada.palavra}": tem ${limpa.length} letras (o certo é de 4 a 10)`);
    if (!entrada.significado) problemas.push(`#${i} "${entrada.palavra}": está sem significado`);
    if (vistas.has(limpa)) problemas.push(`#${i} "${entrada.palavra}": está repetida na lista`);
    vistas.add(limpa);
  });

  PALAVRAS_ACEITAS.forEach((palavra, i) => {
    const limpa = semAcento(palavra);
    if (!/^[A-Z]+$/.test(limpa)) problemas.push(`aceita #${i} "${palavra}": tem caractere que não é letra`);
  });

  if (problemas.length) {
    console.error('[Termo EJAC] Problemas no banco de palavras:\n' + problemas.join('\n'));
  }
})();
