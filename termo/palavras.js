// EJAC — Banco de palavras do "Termo EJAC"
//
// As listas ficam CODIFICADAS em base64, não em texto puro. O motivo é
// prático: a ordem da lista é o calendário do jogo, então quem abrisse
// este arquivo veria a resposta de hoje e a dos próximos dias. Codificar
// não impede ninguém decidido (é tudo client-side, dá pra decodificar no
// console), mas tira o "abri o arquivo e já vi" — que é o caso real aqui,
// ainda mais agora que existe ranking por tempo.
//
// São DUAS listas, com papéis diferentes:
//
//  1. PALAVRAS_EJAC — as palavras que podem ser a resposta do dia. Cada
//     item vira ["PALAVRA", "significado"] depois de decodificado. A ordem
//     É o calendário: a resposta anda um item por dia, do começo pro fim,
//     e recomeça quando acaba.
//
//  2. PALAVRAS_ACEITAS — palavras que valem como TENTATIVA mas nunca
//     serão a resposta (não precisam de significado).
//
// PRA MEXER, use a ferramenta (não edite o base64 na mão):
//
//     node termo/ferramentas/palavras.js ver
//     node termo/ferramentas/palavras.js add "NOVENA" "Oração de nove dias."
//     node termo/ferramentas/palavras.js add-aceita "IGREJINHA"
//
// REGRAS (a ferramenta confere e o jogo também avisa no console):
//  - Só letras de A a Z (acento à vontade) — nada de espaço, hífen ou número
//  - De 4 a 10 letras, sempre
//  - O acento é só pra exibição: quem joga digita sem acento
//  - Acrescentar no FIM de PALAVRAS_EJAC é seguro; inserir no meio desloca
//    o calendário de todas as palavras seguintes

// Base64 -> texto, respeitando acento (atob sozinho devolve bytes crus).
function ejacDecodificar(b64) {
  const bytes = Uint8Array.from(atob(b64), c => c.charCodeAt(0));
  return new TextDecoder().decode(bytes);
}

